#!/usr/bin/env bash
# Install / repair the Claude + Codex integration for this hub.
#
# - Generates ~/.claude/CLAUDE.md (imports config/AGENTS.md + config/baseline.md +
#   your profile + config/CLAUDE.md) and ~/.codex/AGENTS.md (config/AGENTS.md +
#   baseline + your profile, concatenated — Codex has no @-import) from this repo.
# - Symlinks ~/.claude/{rules,hooks,agents} and ~/.claude/keybindings.json into this repo.
# - Symlinks ~/.agents/skills -> <hub>/skills (the shared skill root for other agents);
#   skipped when the hub itself was cloned to ~/.agents/skills.
# - Runs sync.sh to (re)build the flat ~/.claude/skills mirror.
# - Merges config/settings.base.json into ~/.claude/settings.json (jq):
#     * hooks / statusLine / model / theme: base wins (full overwrite).
#     * permissions.defaultMode: base wins when base sets it.
#     * enabledPlugins / extraKnownMarketplaces: union of existing + base; base
#       wins only on conflicting keys, user-added entries survive.
#     * env / pluginConfigs (only when base sets them): same union, pluginConfigs
#       deep-merged per plugin option. Also creates ~/.claude/.ponytail-band = off
#       once when PonyTail is enabled (ADR 0023).
#     * permissions.allow / permissions.ask: union of existing + base, deduped.
#     * every other existing top-level key (machine/project-specific blocks
#       such as per-machine auto-approval config) is preserved as-is.
#   settings.json is backed up before any write.
#
# Idempotent and safe: never deletes a real file or directory. If a symlink
# or generated-file target already exists as a real file/dir we don't own
# (no "generated by agents-config install.sh" header), it is moved aside to
# <path>.bak.<timestamp> once, then regenerated/relinked.
#
# Profile resolution (which config/profiles/<name>.md to import), in order:
#   1. --profile <name>
#   2. ~/.config/agents-config/profile (persisted by a previous run;
#      the legacy ~/.config/agent-config is migrated automatically)
#   3. `gh api user --jq .login`, lowercased, if config/profiles/<login>.md
#      already exists
#   4. same gh login, if no matching profile exists yet: copy
#      config/profiles/_template.md to config/profiles/<login>.md, print a
#      reminder to fill it in, and use it
#   5. config/profiles/_template.md itself (gh missing/unauthenticated)
# Whatever is resolved is persisted to ~/.config/agents-config/profile.
#
# Usage:
#   ./install.sh [--profile <name>] [--org <name> <git-url>] [--dry-run] [--with-rtk] [--with-rulesync]
#                [--with-integrations] [--with-cli-baselines]
#
#   --profile <name> use config/profiles/<name>.md instead of auto-detecting
#   --org <name> <url> clone a private organization repo into organizations/ (scripts/orgs.sh add);
#                   its index (organizations/INDEX.md) is then imported into the generated files
#   --dry-run       print planned actions only, change nothing
#   --with-rtk      also install rtk (https://github.com/rtk-ai/rtk) (the
#                   hook is config/hooks/rtk.sh)
#   --with-rulesync also (re)generate rulesync output for codexcli, geminicli
#                   and cursor via config/rulesync/
#   --with-integrations also install the user-scope MCP servers in config/mcp.user.json
#                   (tools via uv, registered with `claude mcp add-json --scope user`); ADR 0016
#   --with-cli-baselines also write config/baseline.md as the global instructions of agy
#                   (~/.gemini/GEMINI.md), Copilot, OpenCode (and OpenCode under CAO) for the tools
#                   that are installed (scripts/gen-cli-baselines.sh); ADR 0019

set -euo pipefail

HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export AGENTS_CONFIG_HOME="$HUB"
export AGENT_CONFIG_HOME="$HUB" # legacy name, kept for old scripts
CLAUDE_DIR="${CLAUDE_DIR:-$HOME/.claude}"
CODEX_DIR="${CODEX_DIR:-$HOME/.codex}"
PROFILE_STATE_DIR="${AGENTS_CONFIG_STATE_DIR:-${AGENT_CONFIG_STATE_DIR:-$HOME/.config/agents-config}}"
PROFILE_STATE_FILE="$PROFILE_STATE_DIR/profile"
GENERATED_MARK="generated by agents-config install.sh"
LEGACY_GENERATED_MARK="generated by agent-config install.sh"

DRY_RUN=0
WITH_RTK=0
WITH_RULESYNC=0
WITH_INTEGRATIONS=0
WITH_CLI_BASELINES=0
PROFILE_FLAG=""
ORG_ADD=()

while [ $# -gt 0 ]; do
  case "$1" in
    --profile) PROFILE_FLAG="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --org) [ $# -ge 3 ] || { echo "--org needs <name> <git-url>" >&2; exit 1; }; ORG_ADD=("$2" "$3"); shift 3 ;;
    --with-rtk) WITH_RTK=1; shift ;;
    --with-rulesync) WITH_RULESYNC=1; shift ;;
    --with-integrations) WITH_INTEGRATIONS=1; shift ;;
    --with-cli-baselines) WITH_CLI_BASELINES=1; shift ;;
    -h|--help)
      sed -n '2,55p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "unknown flag: $1" >&2
      exit 1
      ;;
  esac
done

# One-time migration of the state dir from the legacy name.
if [ -d "$HOME/.config/agent-config" ] && [ ! -e "$PROFILE_STATE_DIR" ]; then
  echo "migrate: $HOME/.config/agent-config -> $PROFILE_STATE_DIR"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] mv '$HOME/.config/agent-config' '$PROFILE_STATE_DIR'"
  else
    mkdir -p "$(dirname "$PROFILE_STATE_DIR")"
    mv "$HOME/.config/agent-config" "$PROFILE_STATE_DIR"
  fi
fi

ts() { date +%Y%m%d%H%M%S; }

# ---------------------------------------------------------------------------
# Profile resolution
# ---------------------------------------------------------------------------

resolve_profile() {
  if [ -n "$PROFILE_FLAG" ]; then
    printf '%s' "$PROFILE_FLAG"
    return
  fi

  if [ -f "$PROFILE_STATE_FILE" ]; then
    printf '%s' "$(cat "$PROFILE_STATE_FILE")"
    return
  fi

  # Dry-run skips the state-dir migration, so read the legacy file directly.
  if [ -f "$HOME/.config/agent-config/profile" ]; then
    printf '%s' "$(cat "$HOME/.config/agent-config/profile")"
    return
  fi

  if command -v gh >/dev/null 2>&1; then
    local login
    login="$(gh api user --jq .login 2>/dev/null | tr '[:upper:]' '[:lower:]' || true)"
    if [ -n "$login" ]; then
      if [ -f "$HUB/config/profiles/$login.md" ]; then
        printf '%s' "$login"
        return
      fi
      echo "no profile for GitHub login '$login' yet — copying config/profiles/_template.md to config/profiles/$login.md" >&2
      if [ "$DRY_RUN" -eq 1 ]; then
        echo "  [dry-run] cp '$HUB/config/profiles/_template.md' '$HUB/config/profiles/$login.md'" >&2
      else
        cp "$HUB/config/profiles/_template.md" "$HUB/config/profiles/$login.md"
      fi
      echo "fill in config/profiles/$login.md, then re-run this script." >&2
      printf '%s' "$login"
      return
    fi
  fi

  printf '_template'
}

PROFILE="$(resolve_profile)"
PROFILE_FILE="$HUB/config/profiles/$PROFILE.md"

if [ ! -f "$PROFILE_FILE" ]; then
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "note:    $PROFILE_FILE does not exist yet (dry-run) — previewing with config/profiles/_template.md"
    PROFILE_FILE="$HUB/config/profiles/_template.md"
  else
    echo "profile not found: $PROFILE_FILE" >&2
    echo "create it (cp '$HUB/config/profiles/_template.md' '$PROFILE_FILE') or re-run with --profile <existing-name>." >&2
    exit 1
  fi
fi

echo "== profile: $PROFILE ($PROFILE_FILE) =="
if [ "$DRY_RUN" -eq 1 ]; then
  echo "  [dry-run] write '$PROFILE' to '$PROFILE_STATE_FILE'"
else
  mkdir -p "$PROFILE_STATE_DIR"
  printf '%s\n' "$PROFILE" > "$PROFILE_STATE_FILE"
fi

# ---------------------------------------------------------------------------
# link <target> <link_path> — create or repair a symlink, never deleting a
# real file/dir (backs it up instead).
# ---------------------------------------------------------------------------
link() {
  local target="$1" link_path="$2"

  if [ -L "$link_path" ]; then
    if [ "$(readlink "$link_path")" = "$target" ]; then
      echo "ok:      $link_path -> $target"
      return
    fi
    echo "repair:  $link_path (was -> $(readlink "$link_path"))"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] rm '$link_path' && ln -s '$target' '$link_path'"
    else
      rm -f "$link_path"
      ln -s "$target" "$link_path"
    fi
  elif [ -e "$link_path" ]; then
    local backup="${link_path}.bak.$(ts)"
    echo "backup:  $link_path -> $backup (real file/dir, not deleted)"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] mv '$link_path' '$backup' && ln -s '$target' '$link_path'"
    else
      mkdir -p "$(dirname "$link_path")"
      mv "$link_path" "$backup"
      ln -s "$target" "$link_path"
    fi
  else
    echo "create:  $link_path -> $target"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] ln -s '$target' '$link_path'"
    else
      mkdir -p "$(dirname "$link_path")"
      ln -s "$target" "$link_path"
    fi
  fi
}

# ---------------------------------------------------------------------------
# write_generated <dest> <content> — write a file we own (marked with
# GENERATED_MARK). Backs up a pre-existing file/symlink we don't already own
# exactly once; afterwards regenerates in place with no backup. Idempotent:
# a no-op when the content is already correct.
# ---------------------------------------------------------------------------
write_generated() {
  local dest="$1" content="$2"

  if [ -L "$dest" ]; then
    echo "replace symlink: $dest (was -> $(readlink "$dest"))"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] rm '$dest'"
    else
      rm -f "$dest"
    fi
  elif [ -e "$dest" ] && ! grep -qE "$GENERATED_MARK|$LEGACY_GENERATED_MARK" "$dest" 2>/dev/null; then
    local backup="${dest}.bak.$(ts)"
    echo "backup:  $dest -> $backup (real file, not generated by us)"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] mv '$dest' '$backup'"
    else
      mv "$dest" "$backup"
    fi
  fi

  # Keep blocks other installers own (an org's <!-- name:start --> … <!-- name:end -->), so a re-run does not drop them.
  if [ -f "$dest" ]; then
    local blocks
    blocks="$(awk '/^<!-- [A-Za-z0-9_.-]+:start -->$/{b=1} b{print} /^<!-- [A-Za-z0-9_.-]+:end -->$/{b=0}' "$dest")"
    [ -z "$blocks" ] || content="$content"$'\n\n'"$blocks"
  fi

  if [ -f "$dest" ] && [ "$(cat "$dest" 2>/dev/null)" = "$content" ]; then
    echo "ok:      $dest already up to date"
    return
  fi

  echo "generate: $dest"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] write generated content to '$dest'"
  else
    mkdir -p "$(dirname "$dest")"
    printf '%s\n' "$content" > "$dest"
  fi
}

# ---------------------------------------------------------------------------
# link_rules — ~/.claude/rules holds symlinks to the GLOBAL rules only
# (config/rules/*.md not listed under a stack in config/scopes.json).
# Stack rules are installed per project by scripts/project-agents.sh.
# ---------------------------------------------------------------------------
link_rules() {
  local dir="$CLAUDE_DIR/rules" scopes="$HUB/config/scopes.json" f name
  if [ -L "$dir" ]; then
    echo "replace symlink: $dir (was -> $(readlink "$dir")) with a real dir of per-rule links"
    [ "$DRY_RUN" -eq 1 ] || { rm -f "$dir"; mkdir -p "$dir"; }
  elif [ ! -d "$dir" ]; then
    [ "$DRY_RUN" -eq 1 ] || mkdir -p "$dir"
  fi
  for f in "$HUB"/config/rules/*.md; do
    name="$(basename "$f" .md)"
    if jq -e --arg n "$name" '[.stacks[].rules[]] | index($n)' "$scopes" >/dev/null; then
      if [ -L "$dir/$name.md" ]; then
        echo "remove:  $dir/$name.md (project-scoped)"
        [ "$DRY_RUN" -eq 1 ] || rm -f "$dir/$name.md"
      fi
    else
      link "$f" "$dir/$name.md"
    fi
  done
}

echo
echo "== generated config files =="
if [ "$DRY_RUN" -eq 1 ]; then
  echo "  [dry-run] mkdir -p '$CLAUDE_DIR' '$CODEX_DIR'"
else
  mkdir -p "$CLAUDE_DIR" "$CODEX_DIR"
fi

if [ ${#ORG_ADD[@]} -eq 2 ]; then
  if [ "$DRY_RUN" -eq 1 ]; then echo "  [dry-run] scripts/orgs.sh add ${ORG_ADD[0]} <url>"; else bash "$HUB/scripts/orgs.sh" add "${ORG_ADD[0]}" "${ORG_ADD[1]}"; fi
fi
# Organizations index (local, generated by scripts/orgs.sh): one line per org, read on demand.
ORG_INDEX_IMPORT=""
[ -f "$HUB/organizations/INDEX.md" ] && ORG_INDEX_IMPORT="@$HUB/organizations/INDEX.md"

claude_md_content="$(cat <<EOF
<!-- $GENERATED_MARK — edit the repo, not this file. -->
@$HUB/config/AGENTS.md
@$HUB/config/baseline.md
@$HUB/config/profiles/$PROFILE.md
@$HUB/config/CLAUDE.md
${ORG_INDEX_IMPORT}
EOF
)"
write_generated "$CLAUDE_DIR/CLAUDE.md" "$claude_md_content"

codex_agents_content="$(
  printf '<!-- %s — edit the repo, not this file. -->\n\n' "$GENERATED_MARK"
  cat "$HUB/config/AGENTS.md"
  printf '\n\n'
  cat "$HUB/config/baseline.md"
  printf '\n\n'
  cat "$PROFILE_FILE"
  if [ -f "$HUB/organizations/INDEX.md" ]; then printf '\n\n'; cat "$HUB/organizations/INDEX.md"; fi
)"
write_generated "$CODEX_DIR/AGENTS.md" "$codex_agents_content"

echo
echo "== symlinks =="
link_rules
link "$HUB/config/hooks"     "$CLAUDE_DIR/hooks"
link "$HUB/config/agents"    "$CLAUDE_DIR/agents"
link "$HUB/config/keybindings.json" "$CLAUDE_DIR/keybindings.json"
AGENTS_SKILLS="$HOME/.agents/skills"
if [ ! -L "$AGENTS_SKILLS" ] && [ -d "$AGENTS_SKILLS" ] && [ "$(cd "$AGENTS_SKILLS" && pwd -P)" = "$(cd "$HUB" && pwd -P)" ]; then
  echo "skip:    $AGENTS_SKILLS is the hub itself (cloned there); not linking $HUB/skills"
else
  link "$HUB/skills" "$AGENTS_SKILLS"
fi

echo
echo "== skills mirror (sync.sh) =="
if [ "$DRY_RUN" -eq 1 ]; then
  echo "  [dry-run] '$HUB/sync.sh'"
else
  "$HUB/sync.sh"
fi

echo
echo "== settings.json merge =="
SETTINGS="$CLAUDE_DIR/settings.json"
BASE="$HUB/config/settings.base.json"

if [ ! -f "$SETTINGS" ]; then
  echo "create:  $SETTINGS"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] cp '$BASE' '$SETTINGS'"
  else
    mkdir -p "$CLAUDE_DIR"
    cp "$BASE" "$SETTINGS"
  fi
else
  MERGED="$(jq -s '
    .[0] as $cur | .[1] as $base
    | $cur
    | .model = $base.model
    | .effortLevel = $base.effortLevel
    | .modelSettings = ((.modelSettings // {}) * ($base.modelSettings // {}))
    | .hooks = $base.hooks
    | .statusLine = $base.statusLine
    | .enabledPlugins = (($cur.enabledPlugins // {}) + ($base.enabledPlugins // {}))
    | .extraKnownMarketplaces = (($cur.extraKnownMarketplaces // {}) + ($base.extraKnownMarketplaces // {}))
    | (if $base.env then .env = (($cur.env // {}) + $base.env) else . end)
    | (if $base.pluginConfigs then .pluginConfigs = (($cur.pluginConfigs // {}) * $base.pluginConfigs) else . end)
    | .theme = $base.theme
    | (if $base.permissions.defaultMode then .permissions.defaultMode = $base.permissions.defaultMode else . end)
    | .permissions.allow = ((($cur.permissions.allow // []) + ($base.permissions.allow // [])) | unique)
    | .permissions.ask   = ((($cur.permissions.ask   // []) + ($base.permissions.ask   // [])) | unique)
  ' "$SETTINGS" "$BASE")"

  if [ "$(jq -S . "$SETTINGS")" = "$(jq -S . <<<"$MERGED")" ]; then
    echo "ok:      $SETTINGS already up to date"
  else
    BACKUP="$SETTINGS.bak.$(ts)"
    echo "backup:  $SETTINGS -> $BACKUP"
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "  [dry-run] write merged settings to '$SETTINGS' (after backup)"
    else
      cp "$SETTINGS" "$BACKUP"
      jq . <<<"$MERGED" >"$SETTINGS"
    fi
  fi
fi

# PonyTail (ADR 0023): its band above the prompt starts hidden. The flag is PonyTail's own
# (`/ponytail band` toggles it), so an existing one is never overwritten.
BAND_FLAG="$CLAUDE_DIR/.ponytail-band"
if jq -e '.enabledPlugins["ponytail@ponytail"] == true' "$BASE" >/dev/null 2>&1 && [ ! -e "$BAND_FLAG" ]; then
  echo "create:  $BAND_FLAG (off: PonyTail band hidden)"
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] write 'off' to '$BAND_FLAG'"
  else
    mkdir -p "$CLAUDE_DIR"
    printf 'off\n' >"$BAND_FLAG"
  fi
fi

# Local patches to third-party plugins (idempotent; a plugin update overwrites them, so re-run).
echo
echo "== plugin patches =="
if [ "$DRY_RUN" -eq 1 ]; then
  "$HUB/config/patches/paste-preview-no-autoedit.sh" --dry-run
else
  "$HUB/config/patches/paste-preview-no-autoedit.sh"
fi

if [ "$WITH_INTEGRATIONS" -eq 1 ]; then
  echo
  echo "== integrations (user-scope MCP servers, config/mcp.user.json) =="
  MCP_JSON_SRC="$HUB/config/mcp.user.json"
  OBSIDIAN_VAULT="${OBSIDIAN_VAULT:-$HOME/Documents/Obsidian Vault}"
  # ${OBSIDIAN_VAULT} in the JSON is the only placeholder; resolve it into a temp copy.
  MCP_JSON="$(mktemp)"
  jq --arg v "$OBSIDIAN_VAULT" '.servers |= map_values(.args |= map(if . == "${OBSIDIAN_VAULT}" then $v else . end))' "$MCP_JSON_SRC" >"$MCP_JSON"
  trap 'rm -f "$MCP_JSON"' EXIT
  command -v claude >/dev/null || { echo "skip:    claude CLI not found" >&2; MCP_JSON=""; }
  if [ -n "$MCP_JSON" ]; then
    for name in $(jq -r '.servers | keys[]' "$MCP_JSON"); do
      check="$(jq -r --arg n "$name" '.tools[$n].check // empty' "$MCP_JSON")"
      install_cmd="$(jq -r --arg n "$name" '.tools[$n].install // empty' "$MCP_JSON")"
      post="$(jq -r --arg n "$name" '.tools[$n].post // empty' "$MCP_JSON")"
      if [ -n "$check" ] && ! command -v "$check" >/dev/null; then
        if [ -z "$install_cmd" ]; then echo "skip:    $name ('$check' missing, no install command)"; continue; fi
        if [ "$DRY_RUN" -eq 1 ]; then echo "  [dry-run] $install_cmd"; else echo "running: $install_cmd"; sh -c "$install_cmd"; fi
      fi
      if claude mcp get "$name" >/dev/null 2>&1; then
        echo "ok:      mcp '$name' already registered"
      elif [ "$DRY_RUN" -eq 1 ]; then
        echo "  [dry-run] claude mcp add-json --scope user $name '$(jq -c --arg n "$name" '.servers[$n]' "$MCP_JSON")'"
      else
        claude mcp add-json --scope user "$name" "$(jq -c --arg n "$name" '.servers[$n]' "$MCP_JSON")"
        echo "added:   mcp '$name' (user scope)"
      fi
      [ -n "$post" ] && echo "todo:    $name - $post"
    done
  fi
fi

if [ "$WITH_CLI_BASELINES" -eq 1 ]; then
  echo
  echo "== baseline for other CLIs (agy, Copilot, OpenCode); ADR 0019 =="
  if [ "$DRY_RUN" -eq 1 ]; then
    "$HUB/scripts/gen-cli-baselines.sh" --dry-run
  else
    "$HUB/scripts/gen-cli-baselines.sh"
  fi
fi

if [ "$WITH_RULESYNC" -eq 1 ]; then
  echo
  echo "== rulesync (codexcli, antigravity-cli [Gemini], cursor) =="
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] '$HUB/config/rulesync/build.sh'"
    echo "  [dry-run] pnpm dlx rulesync generate   # reads config/rulesync/rulesync.jsonc"
  else
    "$HUB/config/rulesync/build.sh"
    (cd "$HUB/config/rulesync" && pnpm dlx rulesync generate)
  fi
fi

if [ "$WITH_RTK" -eq 1 ]; then
  echo
  echo "== rtk =="
  RTK_CMD='curl -fsSL https://raw.githubusercontent.com/rtk-ai/rtk/refs/heads/master/install.sh | sh'
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "  [dry-run] $RTK_CMD"
    echo "  (hook already wired: config/hooks/rtk.sh via settings.base.json - no rtk init needed)"
  else
    echo "running: $RTK_CMD"
    sh -c "$RTK_CMD"
    echo "rtk hook is wired via config/hooks/rtk.sh (settings.base.json); restart Claude Code."
  fi
fi

echo
echo "hub: $AGENTS_CONFIG_HOME"
echo "hint: run 'npx ccusage@latest' to see your Claude Code token usage/cost."
