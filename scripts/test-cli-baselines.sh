#!/usr/bin/env bash
# test-cli-baselines.sh - offline checks for gen-cli-baselines.sh. HOME is a temp dir: nothing real is touched.
set -uo pipefail
HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
pass=0; failn=0
check() { if eval "$2"; then pass=$((pass + 1)); echo "ok   $1"; else failn=$((failn + 1)); echo "FAIL $1"; fi; }
GEN="$HUB/scripts/gen-cli-baselines.sh"
# PATH holds only the utilities the script needs, so a copilot/opencode/agy installed on this machine is not seen.
mkdir -p "$W/home" "$W/bin"
for c in bash cat wc tr date mkdir rm mv grep sed dirname readlink sha1sum head; do ln -s "$(command -v "$c")" "$W/bin/$c"; done
run() { HOME="$W/home" COPILOT_HOME="" PATH="$W/bin" bash "$GEN" "$@"; }

out="$(run --dry-run --target gemini)"
check "dry-run writes nothing" '[ ! -e "$W/home/.gemini/GEMINI.md" ] && grep -q "dry-run" <<<"$out"'

run --target gemini >/dev/null
check "gemini: file generated with the baseline and the mark" 'grep -q "generated by agents-config install.sh" "$W/home/.gemini/GEMINI.md" && grep -q "Baseline (no negociable)" "$W/home/.gemini/GEMINI.md"'
check "gemini: all 7 baseline rules are there" '[ "$(grep -c "^[1-7]\. " "$W/home/.gemini/GEMINI.md")" -eq 7 ]'
before="$(sha1sum "$W/home/.gemini/GEMINI.md")"; out="$(run --target gemini)"
check "second run is a no-op" '[ "$before" = "$(sha1sum "$W/home/.gemini/GEMINI.md")" ] && grep -q "already up to date" <<<"$out"'

mkdir -p "$W/home/.config/opencode"; echo "mine" >"$W/home/.config/opencode/AGENTS.md"
run --target opencode >/dev/null
check "a real file we do not own is backed up, not lost" '[ "$(cat "$W"/home/.config/opencode/AGENTS.md.bak.* | head -1)" = "mine" ] && grep -q "generated by agents-config" "$W/home/.config/opencode/AGENTS.md"'

out="$(run)"
check "all: tools that are not installed are skipped" 'grep -q "skip:    copilot" <<<"$out" && grep -q "skip:    opencode-cao" <<<"$out" && [ ! -e "$W/home/.copilot/copilot-instructions.md" ] && [ ! -e "$W/home/.aws/opencode/AGENTS.md" ]'

mkdir -p "$W/home/.aws/opencode"; run >/dev/null
check "all: opencode-cao is written once ~/.aws/opencode exists" 'grep -q "generated by agents-config" "$W/home/.aws/opencode/AGENTS.md"'

COPILOT_HOME="$W/cop" HOME="$W/home" PATH="$W/bin" bash "$GEN" --target copilot >/dev/null
check "copilot honours COPILOT_HOME" '[ -f "$W/cop/copilot-instructions.md" ]'
check "unknown target is rejected" '! run --target nope >/dev/null 2>&1'

echo; echo "passed $pass, failed $failn"
[ "$failn" -eq 0 ]
