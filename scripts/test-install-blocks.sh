#!/usr/bin/env bash
# test-install-blocks.sh - install.sh keeps blocks other installers own (an org's <!-- name:start --> … <!-- name:end -->)
# when it regenerates ~/.claude/CLAUDE.md. HOME is a temp dir: nothing real is touched.
set -uo pipefail
HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
pass=0; failn=0
check() { if eval "$2"; then pass=$((pass + 1)); echo "ok   $1"; else failn=$((failn + 1)); echo "FAIL $1"; fi; }
run() { HOME="$W/home" bash "$HUB/install.sh" --profile _template "$@" 2>&1; }
F="$W/home/.claude/CLAUDE.md"

run >/dev/null
check "first run generates CLAUDE.md with no foreign block" 'grep -q "generated by agents-config" "$F" && ! grep -q ":start -->" "$F"'

printf '\n<!-- acme:start -->\nPolicies of acme:\n@~/.claude/acme/POLICIES.md\n<!-- acme:end -->\n' >>"$F"
run >/dev/null
check "a re-run keeps the foreign block" 'grep -qx "<!-- acme:start -->" "$F" && grep -qx "@~/.claude/acme/POLICIES.md" "$F" && grep -qx "<!-- acme:end -->" "$F"'
check "the generated imports are still there" 'grep -q "config/AGENTS.md" "$F" && grep -q "config/baseline.md" "$F"'
check "no backup was made of our own file" '! ls "$W"/home/.claude/CLAUDE.md.bak.* >/dev/null 2>&1'

before="$(sha1sum "$F")"; out="$(run)"
check "with the block, a re-run is a no-op" '[ "$before" = "$(sha1sum "$F")" ] && grep -q "ok:      .*CLAUDE.md already up to date" <<<"$out"'

sed -i '/acme:start/,/acme:end/d' "$F"; run >/dev/null
check "removing the block by hand is respected" '! grep -q "acme" "$F"'

# ~/.codex/AGENTS.md pastes config/AGENTS.md, which carries its own <!-- intents:start --> block: it must not be duplicated.
C="$W/home/.codex/AGENTS.md"
own="$(grep -c '^<!-- intents:start -->$' "$HUB/config/AGENTS.md")"
run >/dev/null; before="$(sha1sum "$C")"; out="$(run)"
check "a block that is part of the generated content is not duplicated" '[ "$(grep -c "^<!-- intents:start -->$" "$C")" -eq "$own" ]'
check "codex file: a re-run is a no-op" '[ "$before" = "$(sha1sum "$C")" ] && grep -q "ok:      .*AGENTS.md already up to date" <<<"$out"'
printf '\n<!-- intents:start -->\nstale copy\n<!-- intents:end -->\n' >>"$C"; run >/dev/null
check "a stale copy of our own block is cleaned up" '[ "$(grep -c "^<!-- intents:start -->$" "$C")" -eq "$own" ] && ! grep -q "stale copy" "$C"'

echo; echo "passed $pass, failed $failn"
[ "$failn" -eq 0 ]
