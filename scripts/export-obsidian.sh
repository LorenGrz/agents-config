#!/usr/bin/env bash
# export-obsidian.sh - generate documentation of this hub into an Obsidian vault.
#   <vault>/agents-config/agents-config.md   overview, structure, install flow, agent routing
#   <vault>/agents-config/skills/<name>.md   one note per skill (hub + enabled plugins) + _index.md
#   <vault>/agents-config/integraciones.md   plugins, MCP servers, permissions, connectors, patches
#   <vault>/agents-config/pendientes.md      not-installed-on-purpose list + ideas
#
# Usage: export-obsidian.sh [--dry-run] [--vault <path>]
#   default vault: ${OBSIDIAN_VAULT:-$HOME/Documents/Obsidian Vault}
#
# Idempotent: only files starting with the generated marker are overwritten; any other file in
# <vault>/agents-config/ is left alone (a warning is printed instead).
set -euo pipefail

HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASE="$HUB/config/settings.base.json"
MCP="$HUB/config/mcp.user.json"
MARKER='<!-- generated by scripts/export-obsidian.sh - do not edit by hand -->'
VAULT="${OBSIDIAN_VAULT:-$HOME/Documents/Obsidian Vault}"
DRY=0
TODAY="$(date +%Y-%m-%d)"

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1; shift ;;
    --vault) [ $# -ge 2 ] || { echo "Error: --vault needs a path" >&2; exit 1; }; VAULT="$2"; shift 2 ;;
    -h|--help) sed -n 2,13p "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Error: unknown option $1" >&2; exit 1 ;;
  esac
done
command -v jq >/dev/null || { echo "Error: jq is required" >&2; exit 1; }

OUT="$VAULT/agents-config"
PLUGINS="$HOME/.claude/plugins/cache"
written=0
skipped=0

tilde() { printf '%s' "${1/#"$HOME"/\~}"; }

# write_note <relative path under $OUT>; content on stdin (marker is added after the frontmatter, $HOME masked as ~)
write_note() {
  local rel="$1" target="$OUT/$1" content
  content="$(cat)"
  content="${content//"$HOME"/\~}"
  if [ -e "$target" ] && ! head -n 20 "$target" | grep -qxF -- "$MARKER"; then
    echo "warn: $rel exists without the generated marker, not touched" >&2
    skipped=$((skipped + 1))
    return 0
  fi
  written=$((written + 1))
  if [ "$DRY" -eq 1 ]; then
    echo "would write: agents-config/$rel"
    return 0
  fi
  mkdir -p "$(dirname "$target")"
  # Marker goes right after the closing '---' of the frontmatter so Obsidian still reads the properties.
  printf '%s\n' "$content" | awk -v m="$MARKER" 'NR == 1 && $0 != "---" { print m } { print } $0 == "---" && NR > 1 && !done { print m; done = 1 }' >"$target"
}

# fm_field <file> <field>: value of a top-level frontmatter field (handles folded/literal blocks)
fm_field() {
  awk -v key="$2" '
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    {
      if (inblock && ($0 ~ /^[ \t]/ || $0 == "")) { sub(/^[ \t]+/, ""); val = val (val == "" ? "" : " ") $0; next }
      inblock = 0
      if (index($0, key ":") == 1) {
        v = substr($0, length(key) + 2); sub(/^[ \t]+/, "", v)
        if (v ~ /^[>|][-+]?$/) { inblock = 1; val = ""; next }
        val = v; found = 1
      }
    }
    END { gsub(/^"|"$/, "", val); gsub(/^'\''|'\''$/, "", val); print val }
  ' "$1"
}

yaml_q() { local s="${1//\\/\\\\}"; printf '"%s"' "${s//\"/\\\"}"; }

# ---- skills ---------------------------------------------------------------------------------
declare -A USED=()
declare -A GROUP_ITEMS=()
GROUPS_ORDER=()

# add_skill <SKILL.md path> <origin label> <category/origin text>
add_skill() {
  local file="$1" origin="$2" name desc slug trig
  name="$(fm_field "$file" name)"
  [ -n "$name" ] || name="$(basename "$(dirname "$file")")"
  desc="$(fm_field "$file" description)"
  slug="$(printf '%s' "$name" | tr -c 'A-Za-z0-9._\n-' '-')"
  if [ -n "${USED[$slug]:-}" ]; then slug="${origin//[^A-Za-z0-9._-]/-}--$slug"; fi
  USED[$slug]=1
  if [[ "$desc" == *"Use when"* ]]; then trig="Use when${desc#*Use when}"
  elif [[ "$desc" == *"Use this"* ]]; then trig="Use this${desc#*Use this}"
  else trig="$desc"; fi
  local kind="hub"
  [[ "$origin" == plugin:* ]] && kind="plugin"
  write_note "skills/$slug.md" <<NOTE
---
title: $(yaml_q "$name")
tags: [agents-config, skill, $kind]
generated: $TODAY
---

# $name

- **Descripción:** ${desc:-sin descripción}
- **Categoría / origen:** $origin
- **Fuente:** \`$(tilde "$file")\`
- **Cuándo se activa:** ${trig:-sin descripción}

Volver a [[agents-config/skills/_index|índice de skills]] · [[agents-config/agents-config|agents-config]]
NOTE
  if [ -z "${GROUP_ITEMS[$origin]+x}" ]; then GROUPS_ORDER+=("$origin"); GROUP_ITEMS[$origin]=""; fi
  GROUP_ITEMS[$origin]+="- [[agents-config/skills/$slug|$name]]"$'\n'
}

declare -A CAT_COUNT=()
while IFS= read -r f; do
  d="$(dirname "$f")"
  cat="$(basename "$(dirname "$d")")"
  CAT_COUNT[$cat]=$(( ${CAT_COUNT[$cat]:-0} + 1 ))
  add_skill "$f" "$cat" 
done < <(find "$HUB" -mindepth 3 -maxdepth 3 -name SKILL.md -not -path "$HUB/config/*" -not -path "$HUB/.git/*" | sort)

while IFS= read -r key; do
  pname="${key%@*}"
  mkt="${key#*@}"
  # newest installed version of that plugin, if any
  vdir="$(find "$PLUGINS/$mkt/$pname" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | sort -V | tail -n 1 || true)"
  [ -n "$vdir" ] || continue
  while IFS= read -r f; do
    add_skill "$f" "plugin:$pname"
  done < <(find "$vdir" -name SKILL.md -not -path '*/node_modules/*' 2>/dev/null | sort)
done < <(jq -r '.enabledPlugins | to_entries[] | select(.value == true) | .key' "$BASE")

{
  cat <<HEAD
---
title: "Índice de skills"
tags: [agents-config, skills, indice]
generated: $TODAY
---

# Índice de skills

Total: ${#USED[@]} skills. Volver a [[agents-config/agents-config|agents-config]].
HEAD
  for g in "${GROUPS_ORDER[@]}"; do
    printf '\n## %s\n\n%s' "$g" "${GROUP_ITEMS[$g]}"
  done
} | write_note "skills/_index.md"

# ---- agents-config.md -----------------------------------------------------------------------
intro="$(awk 'NR > 1 && /^[A-Za-z*]/ && !/^#/ { p = 1 } p && /^$/ { exit } p { print }' "$HUB/README.md" | tr '\n' ' ' | sed 's/ *$//')"
routing="$(awk '/^## Agent Routing/ { s = 1; next } s && /^### / { exit } s && /^## / { exit } s' "$HUB/config/CLAUDE.md" | sed '/^$/N;/^\n$/D')"
structure=""
for c in $(printf '%s\n' "${!CAT_COUNT[@]}" | sort); do
  structure+="- \`$c/\` — ${CAT_COUNT[$c]} skills"$'\n'
done

write_note "agents-config.md" <<NOTE
---
title: "agents-config"
tags: [agents-config, hub]
generated: $TODAY
---

# agents-config

$intro

## Estructura de primer nivel

Directorios de categoría con la cantidad de skills de cada uno:

$structure
Además: \`config/\` (instrucciones, reglas, hooks, subagentes, settings base), \`scripts/\`, \`docs/\` (ADRs, specs, planes), \`organizations/\` y \`packs/\`.

## Flujo de instalación

1. \`git clone https://github.com/LorenGrz/agents-config ~/.agents/skills\`
2. \`install.sh --dry-run\` para previsualizar sin cambiar nada.
3. \`install.sh --profile <nombre>\` instala config, reglas, hooks, subagentes y skills.

Flags de \`install.sh\`:

- \`--profile <nombre>\`: perfil personal a usar.
- \`--dry-run\`: muestra qué haría, sin cambios.
- \`--org <nombre> <git-url>\`: registra una organización.
- \`--with-rtk\`: instala la integración rtk.
- \`--with-rulesync\`: genera reglas para otros agentes con rulesync.
- \`--with-integrations\`: instala plugins y servidores MCP de usuario (ver [[agents-config/integraciones|integraciones]]).

## Routing de agentes

Resumen de "Agent Routing" en \`config/CLAUDE.md\`:

$routing

## Navegación

- [[agents-config/integraciones|Integraciones]]
- [[agents-config/pendientes|Pendientes]]
- [[agents-config/skills/_index|Índice de skills]]
NOTE

# ---- integraciones.md -----------------------------------------------------------------------
plugins_md="$(jq -r '
  (.extraKnownMarketplaces // {}) as $m
  | .enabledPlugins | to_entries[]
  | (.key | split("@")) as $p
  | "| \($p[0]) | \($p[1]) | \(if .value then "activo" else "desactivado" end) | \($m[$p[1]].source.repo // "—") |"' "$BASE")"
mcp_md="$(jq -r '
  . as $r | .servers | to_entries[]
  | "- **\(.key)**: `\(.value.command) \(.value.args | join(" "))`" +
    (if ($r.tools[.key].install // "") != "" then "\n  - instalación: `\($r.tools[.key].install)`" else "" end) +
    (([.value.args[] | select(test("@[0-9]+\\.[0-9]"))] | first // "") as $pin
      | if $pin != "" then "\n  - versión fijada: `\($pin)`" else "" end) +
    (if ($r.tools[.key].post // "") != "" then "\n  - post-instalación: \($r.tools[.key].post)" else "" end)' "$MCP")"

ask_group() { # <title> <jq regex over the entry>
  local items
  items="$(jq -r --arg re "$2" '.permissions.ask[] | select(test($re))' "$BASE" | sed 's/^/  - `/; s/$/`/')"
  [ -n "$items" ] && printf -- '- **%s**\n%s\n' "$1" "$items"
  return 0
}
ask_md="$(
  ask_group Slack 'Slack'
  ask_group Gmail 'Gmail'
  ask_group Calendar 'Calendar'
  ask_group Drive 'Drive'
  ask_group 'Jira/Confluence' 'Atlassian'
  ask_group GitHub 'GitHub'
  ask_group Obsidian 'obsidian'
  ask_group AWS '^Bash\(aws '
  ask_group Otros '^(?!.*(Slack|Gmail|Calendar|Drive|Atlassian|GitHub|obsidian|^Bash\(aws )).*$'
)"

write_note "integraciones.md" <<NOTE
---
title: "Integraciones"
tags: [agents-config, integraciones, mcp, plugins]
generated: $TODAY
---

# Integraciones

Generado desde \`config/settings.base.json\` y \`config/mcp.user.json\`. Decisión de diseño: \`docs/decisions/0016-integrations-plugins-mcp.md\`.

## Plugins

| Plugin | Marketplace | Estado | Repo del marketplace |
|---|---|---|---|
$plugins_md

## Servidores MCP (scope usuario)

Se aplican con \`install.sh --with-integrations\`. Sin secretos en el repo.

$mcp_md

## Permisos que piden confirmación (\`permissions.ask\`)

$ask_md

## Conectores de cuenta

Slack, Atlassian, GitHub, Gmail, Google Calendar y Google Drive vienen de claude.ai (cuenta); no están declarados en archivos del repo.

## Parche local de paste-preview

\`config/patches/paste-preview-no-autoedit.sh\` comenta la línea que abre el editor en cada pegado de imagen (el botón "Edit" sigue disponible). Es idempotente; una actualización del plugin lo pisa e \`install.sh\` lo reaplica.

## Desinstalar

- Plugin: \`claude plugin uninstall <nombre>\`
- Servidor MCP: \`claude mcp remove <nombre>\`
- NotebookLM: \`uv tool uninstall notebooklm-py\`

Ver también [[agents-config/agents-config|agents-config]] y [[agents-config/pendientes|pendientes]].
NOTE

