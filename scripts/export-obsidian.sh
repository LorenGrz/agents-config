if [ "$DRY" -eq 1 ]; then
  echo "dry-run: $written notes would be written, $skipped skipped (vault: $(tilde "$VAULT"))"
else
  echo "export-obsidian: $written notes written, $skipped skipped in $(tilde "$OUT")"
fi
